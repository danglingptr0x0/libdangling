uint32_t ldg_hash_poseidon2_compute(const ldg_math_field_elem_t *src, uint64_t cunt, ldg_math_field_elem_t *out)
{
    ldg_math_field_elem_t state[LDG_HASH_POSEIDON2_WIDTH] = LDG_ARR_ZERO_INIT;
    uint32_t ret = LDG_ERR_AOK;
    uint32_t idx = 0;
    uint64_t done = 0;
    uint64_t taken = 0;

    if (LDG_UNLIKELY(!out)) { return LDG_ERR_FUNC_ARG_NULL; }

    if (LDG_UNLIKELY(cunt > 0 && !src)) { return LDG_ERR_FUNC_ARG_NULL; }

    for (idx = 0; idx < LDG_HASH_POSEIDON2_WIDTH; idx++) { state[idx] = LDG_MATH_FIELD_ADD_IDENT; }

    state[LDG_HASH_POSEIDON2_RATE] = ldg_math_field_reduce(cunt);

    while (done < cunt)
    {
        taken = cunt - done;

        if (taken > LDG_HASH_POSEIDON2_RATE) { taken = LDG_HASH_POSEIDON2_RATE; }

        for (idx = 0; idx < LDG_HASH_POSEIDON2_RATE; idx++) { if (idx < taken) { state[idx] = ldg_math_field_add(state[idx], ldg_math_field_reduce(src[done + idx])); } }

        ret = ldg_hash_poseidon2_permute(state);

        if (LDG_UNLIKELY(ret != LDG_ERR_AOK)) { return ret; }

        done += taken;
    }

    if (cunt == 0)
    {
        ret = ldg_hash_poseidon2_permute(state);

        if (LDG_UNLIKELY(ret != LDG_ERR_AOK)) { return ret; }
    }

    for (idx = 0; idx < LDG_HASH_POSEIDON2_OUT_CUNT; idx++) { out[idx] = state[idx]; }

    return LDG_ERR_AOK;
}

uint32_t ldg_hash_poseidon2_pair_compress(const ldg_math_field_elem_t *lhs, const ldg_math_field_elem_t *rhs, ldg_math_field_elem_t *out)
{
    ldg_math_field_elem_t state[LDG_HASH_POSEIDON2_WIDTH] = LDG_ARR_ZERO_INIT;
    uint32_t ret = LDG_ERR_AOK;
    uint32_t idx = 0;

    if (LDG_UNLIKELY(!lhs || !rhs || !out)) { return LDG_ERR_FUNC_ARG_NULL; }

    for (idx = 0; idx < LDG_HASH_POSEIDON2_OUT_CUNT; idx++)
    {
        state[idx] = ldg_math_field_reduce(lhs[idx]);
        state[LDG_HASH_POSEIDON2_OUT_CUNT + idx] = ldg_math_field_reduce(rhs[idx]);
    }

    for (idx = LDG_HASH_POSEIDON2_RATE; idx < LDG_HASH_POSEIDON2_WIDTH; idx++) { state[idx] = LDG_MATH_FIELD_ADD_IDENT; }

    ret = ldg_hash_poseidon2_permute(state);

    if (LDG_UNLIKELY(ret != LDG_ERR_AOK)) { return ret; }

    for (idx = 0; idx < LDG_HASH_POSEIDON2_OUT_CUNT; idx++) { out[idx] = state[idx]; }

    return LDG_ERR_AOK;
}
