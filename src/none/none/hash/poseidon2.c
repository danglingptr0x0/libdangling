static ldg_math_field_elem_t poseidon2_sbox_get(ldg_math_field_elem_t val)
{
    ldg_math_field_elem_t square = 0;
    ldg_math_field_elem_t quartic = 0;

    square = ldg_math_field_mul(val, val);
    quartic = ldg_math_field_mul(square, square);

    return ldg_math_field_mul(ldg_math_field_mul(quartic, square), val);
}

static void poseidon2_blk_mix(ldg_math_field_elem_t *blk)
{
    ldg_math_field_elem_t sum_ab = 0;
    ldg_math_field_elem_t sum_cd = 0;
    ldg_math_field_elem_t mix_b = 0;
    ldg_math_field_elem_t mix_d = 0;
    ldg_math_field_elem_t quad_cd = 0;
    ldg_math_field_elem_t quad_ab = 0;

    sum_ab = ldg_math_field_add(blk[LDG_HASH_POSEIDON2_LANE_A], blk[LDG_HASH_POSEIDON2_LANE_B]);
    sum_cd = ldg_math_field_add(blk[LDG_HASH_POSEIDON2_LANE_C], blk[LDG_HASH_POSEIDON2_LANE_D]);
    mix_b = ldg_math_field_add(ldg_math_field_mul(blk[LDG_HASH_POSEIDON2_LANE_B], LDG_HASH_POSEIDON2_DOUBLE), sum_cd);
    mix_d = ldg_math_field_add(ldg_math_field_mul(blk[LDG_HASH_POSEIDON2_LANE_D], LDG_HASH_POSEIDON2_DOUBLE), sum_ab);
    quad_cd = ldg_math_field_add(ldg_math_field_mul(sum_cd, LDG_HASH_POSEIDON2_QUAD), mix_d);
    quad_ab = ldg_math_field_add(ldg_math_field_mul(sum_ab, LDG_HASH_POSEIDON2_QUAD), mix_b);

    blk[LDG_HASH_POSEIDON2_LANE_A] = ldg_math_field_add(mix_d, quad_ab);
    blk[LDG_HASH_POSEIDON2_LANE_B] = quad_ab;
    blk[LDG_HASH_POSEIDON2_LANE_C] = ldg_math_field_add(mix_b, quad_cd);
    blk[LDG_HASH_POSEIDON2_LANE_D] = quad_cd;
}

static void poseidon2_full_mix(ldg_math_field_elem_t *state)
{
    ldg_math_field_elem_t blk_sum[LDG_HASH_POSEIDON2_BLK_WIDTH] = LDG_ARR_ZERO_INIT;
    uint32_t blk = 0;
    uint32_t lane = 0;

    for (blk = 0; blk < LDG_HASH_POSEIDON2_BLK_CUNT; blk++) { poseidon2_blk_mix(state + (blk * LDG_HASH_POSEIDON2_BLK_WIDTH)); }

    for (lane = 0; lane < LDG_HASH_POSEIDON2_BLK_WIDTH; lane++)
    {
        blk_sum[lane] = LDG_MATH_FIELD_ADD_IDENT;

        for (blk = 0; blk < LDG_HASH_POSEIDON2_BLK_CUNT; blk++) { blk_sum[lane] = ldg_math_field_add(blk_sum[lane], state[(blk * LDG_HASH_POSEIDON2_BLK_WIDTH) + lane]); }
    }

    for (blk = 0; blk < LDG_HASH_POSEIDON2_BLK_CUNT; blk++) { for (lane = 0; lane < LDG_HASH_POSEIDON2_BLK_WIDTH; lane++) { state[(blk * LDG_HASH_POSEIDON2_BLK_WIDTH) + lane] = ldg_math_field_add(state[(blk * LDG_HASH_POSEIDON2_BLK_WIDTH) + lane], blk_sum[lane]); } }
}

static void poseidon2_diag_mix(ldg_math_field_elem_t *state, const ldg_math_field_elem_t *diag)
{
    ldg_math_field_elem_t sum = LDG_MATH_FIELD_ADD_IDENT;
    uint32_t idx = 0;

    for (idx = 0; idx < LDG_HASH_POSEIDON2_WIDTH; idx++) { sum = ldg_math_field_add(sum, state[idx]); }

    for (idx = 0; idx < LDG_HASH_POSEIDON2_WIDTH; idx++) { state[idx] = ldg_math_field_add(ldg_math_field_mul(state[idx], diag[idx]), sum); }
}

static void poseidon2_full_round(ldg_math_field_elem_t *state, const ldg_math_field_elem_t *rc)
{
    uint32_t idx = 0;

    for (idx = 0; idx < LDG_HASH_POSEIDON2_WIDTH; idx++) { state[idx] = poseidon2_sbox_get(ldg_math_field_add(state[idx], rc[idx])); }

    poseidon2_full_mix(state);
}

static void poseidon2_part_round(ldg_math_field_elem_t *state, ldg_math_field_elem_t rc, const ldg_math_field_elem_t *diag)
{
    state[0] = poseidon2_sbox_get(ldg_math_field_add(state[0], rc));
    poseidon2_diag_mix(state, diag);
}

